"""Coordinates end-to-end What-If impact analysis and report compilation."""
import json
import time
from typing import Dict, Any, Optional
import networkx as nx

from repomind.analysis.change_parser import ChangeParser
from repomind.analysis.impact_analyzer import ImpactAnalyzer, ImpactReportData
from repomind.retrieval.hybrid_retriever import HybridRetriever
from repomind.llm.answer_generator import AnswerGenerator


class WhatIfReportCoordinator:
    """Orchestrates parsing, neighborhood impact tracing, hybrid retrieval, and LLM synthesis."""

    def __init__(
        self,
        graph: nx.DiGraph,
        hybrid_retriever: HybridRetriever,
        answer_generator: Optional[AnswerGenerator] = None
    ):
        self.graph = graph
        self.retriever = hybrid_retriever
        self.answer_generator = answer_generator or AnswerGenerator()
        self.analyzer = ImpactAnalyzer(graph)

    def run_analysis(self, hypothesis: str, max_depth: int = 3) -> Dict[str, Any]:
        """Execute complete explainable What-If analysis workflow."""
        start_time = time.time()

        # Step 1: Parse proposed change
        parsed_change = ChangeParser.parse(hypothesis, self.graph)

        # Step 2: Trace structural upstream and downstream impact
        impact_data: ImpactReportData = self.analyzer.analyze(parsed_change, max_depth=max_depth)

        # Step 3: Retrieve relevant code and documentation chunks
        retrieval_res = self.retriever.retrieve(
            query=hypothesis,
            mode="hybrid",
            top_k=5,
            graph_depth=max_depth
        )

        # Step 4: Augment prompt context with the computed impact paths
        path_texts = [p["path_text"] for p in impact_data.impact_paths]
        if path_texts:
            augmented_paths = "\n".join(f"- {p}" for p in path_texts)
            retrieval_res["prompt_context"] += f"\n\n### Computed Dependency Impact Paths:\n{augmented_paths}"

        # Step 5: Generate LLM analysis report
        llm_res = self.answer_generator.generate_whatif_report(hypothesis, retrieval_res)
        elapsed = round(time.time() - start_time, 3)

        return {
            "hypothesis": hypothesis,
            "action": parsed_change.action,
            "target_entity": parsed_change.target_entity,
            "replacement_entity": parsed_change.replacement_entity,
            "risk_level": impact_data.risk_level,
            "report_markdown": llm_res.get("report_markdown", ""),
            "target_nodes": impact_data.target_nodes,
            "direct_affected": impact_data.direct_affected,
            "inferred_affected": impact_data.inferred_affected,
            "tests_to_update": impact_data.tests_to_update,
            "configs_to_update": impact_data.configs_to_update,
            "impact_paths": impact_data.impact_paths,
            "citations": retrieval_res.get("citations", []),
            "impact_subgraph": impact_data.impact_subgraph,
            "latency": elapsed,
            "model_used": llm_res.get("model_used", "Local Grounded Engine")
        }

    @staticmethod
    def export_report_markdown(analysis_res: Dict[str, Any]) -> str:
        """Format analysis dictionary into a clean downloadable Markdown document."""
        return f"""# RepoMind What-If Impact Report
**Hypothesis:** {analysis_res.get('hypothesis')}
**Action:** {analysis_res.get('action', '').upper()} | **Target:** {analysis_res.get('target_entity')} | **Risk Level:** {analysis_res.get('risk_level')}
**Analysis Engine:** {analysis_res.get('model_used')} | **Latency:** {analysis_res.get('latency')}s

---

{analysis_res.get('report_markdown', '')}

---
### Structural Impact Metrics
- **Directly Affected Components:** {len(analysis_res.get('direct_affected', []))}
- **Inferred / Transitive Components:** {len(analysis_res.get('inferred_affected', []))}
- **Tests Requiring Updates:** {len(analysis_res.get('tests_to_update', []))}
- **Configuration Files Impacted:** {len(analysis_res.get('configs_to_update', []))}
- **Documented Relationship Paths:** {len(analysis_res.get('impact_paths', []))}

*Generated by RepoMind Explainable GraphRAG Platform.*
"""
